import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  createWorktree,
  listWorktrees,
  removeWorktree,
} from './worktreeManager';

/**
 * 真实 git 仓库上的 worktree 建删测试：不 mock git，全部落到临时目录，
 * 每个测试自建自清，断言的是真实文件系统与真实分支状态。
 */

function git(cwd: string, args: string[]): { status: number | null; out: string } {
  const r = spawnSync('git', args, { cwd, encoding: 'utf-8' });
  return { status: r.status, out: `${r.stdout ?? ''}${r.stderr ?? ''}` };
}

function makeRepo(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sa-wt-'));
  assert.equal(git(dir, ['init', '-q', '-b', 'main']).status, 0);
  const commit = git(dir, [
    '-c',
    'user.email=test@example.invalid',
    '-c',
    'user.name=SuperAgentTest',
    'commit',
    '--allow-empty',
    '-m',
    'init',
  ]);
  assert.equal(commit.status, 0, `初始化提交失败: ${commit.out}`);
  return dir;
}

function cleanup(dir: string): void {
  fs.rmSync(dir, { recursive: true, force: true });
}

test('worktree: 非 git 目录明确报 not_a_git_repo，不静默成功', (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sa-wt-bad-'));
  t.after(() => cleanup(dir));
  const r = createWorktree({ repoRoot: dir, taskId: 'task-1' });
  assert.equal(r.ok, false);
  if (!r.ok) assert.equal(r.code, 'not_a_git_repo');
});

test('worktree: taskId 路径逃逸被拒（../ 与分隔符）', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));
  for (const bad of ['../evil', 'a/b', '..', '', 'task 1', '-rf']) {
    const r = createWorktree({ repoRoot: repo, taskId: bad });
    assert.equal(r.ok, false, `taskId=${JSON.stringify(bad)} 应被拒`);
    if (!r.ok) assert.equal(r.code, 'invalid_task_id', `taskId=${bad}`);
  }
  // 拒绝后不得留下任何目录
  assert.equal(fs.existsSync(path.join(repo, '.worktrees', 'evil')), false);
});

test('worktree: baseRef 以 - 开头或含 .. 被拒', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));
  for (const bad of ['-x', 'a..b', '--force']) {
    const r = createWorktree({ repoRoot: repo, taskId: 'task-ref', baseRef: bad });
    assert.equal(r.ok, false, `baseRef=${bad} 应被拒`);
    if (!r.ok) assert.equal(r.code, 'invalid_base_ref');
  }
});

test('worktree: 创建后目录、.git 链接、分支、HEAD 均真实存在', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const r = createWorktree({ repoRoot: repo, taskId: 'task-2041-b1', baseRef: 'main' });
  assert.equal(r.ok, true, r.ok ? '' : `${r.code}: ${r.message}`);
  if (!r.ok) return;

  assert.equal(r.value.taskId, 'task-2041-b1');
  assert.equal(r.value.branch, 'agent/task-2041-b1');
  assert.equal(r.value.baseRef, 'main');
  assert.match(r.value.headSha, /^[0-9a-f]{40}$/);
  assert.equal(fs.existsSync(r.value.path), true);
  assert.equal(fs.existsSync(path.join(r.value.path, '.git')), true);

  // 分支真的在 refs/heads 下
  const branch = git(repo, ['rev-parse', '--verify', '--quiet', 'refs/heads/agent/task-2041-b1']);
  assert.equal(branch.status, 0, `分支未创建: ${branch.out}`);
});

test('worktree: 工作区物理隔离——worktree 内改动不污染主仓工作区', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const r = createWorktree({ repoRoot: repo, taskId: 'task-iso' });
  assert.equal(r.ok, true);
  if (!r.ok) return;

  fs.writeFileSync(path.join(r.value.path, 'agent-output.txt'), 'generated by agent\n', 'utf-8');

  // worktree 内可见
  assert.equal(fs.existsSync(path.join(r.value.path, 'agent-output.txt')), true);
  // 主仓工作区不可见
  assert.equal(fs.existsSync(path.join(repo, 'agent-output.txt')), false);
  // 主仓 git status 仍干净
  const status = git(repo, ['status', '--porcelain']);
  assert.equal(status.out.trim(), '', `主仓工作区被污染: ${status.out}`);
});

test('worktree: 同 taskId 重复创建幂等，不重复 add、不报错', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const first = createWorktree({ repoRoot: repo, taskId: 'task-idem' });
  assert.equal(first.ok, true);
  const second = createWorktree({ repoRoot: repo, taskId: 'task-idem' });
  assert.equal(second.ok, true);
  if (!first.ok || !second.ok) return;
  assert.equal(second.value.path, first.value.path);

  const list = listWorktrees(repo, path.join(repo, '.worktrees'));
  assert.equal(list.ok, true);
  if (list.ok) {
    assert.equal(list.value.filter((h) => h.taskId === 'task-idem').length, 1);
  }
});

test('worktree: list 只返回 root 下的工作树（主仓自身被排除）', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  assert.equal(createWorktree({ repoRoot: repo, taskId: 'task-a' }).ok, true);
  assert.equal(createWorktree({ repoRoot: repo, taskId: 'task-b' }).ok, true);

  const list = listWorktrees(repo, path.join(repo, '.worktrees'));
  assert.equal(list.ok, true);
  if (!list.ok) return;
  const ids = list.value.map((h) => h.taskId).sort();
  assert.deepEqual(ids, ['task-a', 'task-b']);
  assert.equal(
    list.value.some((h) => h.path === repo),
    false,
    '主仓自身不应出现在受管工作树列表',
  );
});

test('worktree: 目标路径被非工作树内容占用时拒绝，不覆盖用户文件', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const occupied = path.join(repo, '.worktrees', 'task-busy');
  fs.mkdirSync(occupied, { recursive: true });
  fs.writeFileSync(path.join(occupied, 'user-data.txt'), 'do not delete\n', 'utf-8');

  const r = createWorktree({ repoRoot: repo, taskId: 'task-busy' });
  assert.equal(r.ok, false);
  if (!r.ok) assert.equal(r.code, 'path_conflict');
  // 用户文件必须完好
  assert.equal(fs.readFileSync(path.join(occupied, 'user-data.txt'), 'utf-8'), 'do not delete\n');
});

test('worktree: baseRef 不存在时如实失败且不留空目录', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const r = createWorktree({ repoRoot: repo, taskId: 'task-noref', baseRef: 'no-such-branch' });
  assert.equal(r.ok, false);
  if (!r.ok) assert.equal(r.code, 'git_failed');
  assert.equal(fs.existsSync(path.join(repo, '.worktrees', 'task-noref')), false);
  const list = listWorktrees(repo, path.join(repo, '.worktrees'));
  assert.equal(list.ok, true);
  if (list.ok) assert.equal(list.value.length, 0);
});

test('worktree: 删除后目录消失、分支默认保留作审计证据', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const created = createWorktree({ repoRoot: repo, taskId: 'task-del' });
  assert.equal(created.ok, true);
  if (!created.ok) return;

  const removed = removeWorktree({ repoRoot: repo, taskId: 'task-del' });
  assert.equal(removed.ok, true, removed.ok ? '' : `${removed.code}: ${removed.message}`);
  if (!removed.ok) return;
  assert.equal(removed.value.removed, true);
  assert.equal(removed.value.branchDeleted, false);
  assert.equal(fs.existsSync(created.value.path), false);
  assert.equal(
    git(repo, ['rev-parse', '--verify', '--quiet', 'refs/heads/agent/task-del']).status,
    0,
    '默认应保留分支',
  );
});

test('worktree: deleteBranch=true 时连带删除分支', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  assert.equal(createWorktree({ repoRoot: repo, taskId: 'task-purg' }).ok, true);
  const removed = removeWorktree({
    repoRoot: repo,
    taskId: 'task-purg',
    deleteBranch: true,
  });
  assert.equal(removed.ok, true);
  if (!removed.ok) return;
  assert.equal(removed.value.branchDeleted, true);
  assert.notEqual(
    git(repo, ['rev-parse', '--verify', '--quiet', 'refs/heads/agent/task-purg']).status,
    0,
    '分支应已删除',
  );
});

test('worktree: 删除未登记的 taskId 返回 not_found 且不做破坏性兜底', (t) => {
  const repo = makeRepo();
  t.after(() => cleanup(repo));

  const r = removeWorktree({ repoRoot: repo, taskId: 'task-ghost' });
  assert.equal(r.ok, false);
  if (!r.ok) assert.equal(r.code, 'not_found');
});
